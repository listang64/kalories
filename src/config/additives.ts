const BY_CODE = new Map(TABLE.map(([code, name, risk]) => [code, { name, risk }]))

export interface Additive {
  code: string
  name: string
  risk: Risk | null
}

export function additiveFromTag(tag: string): Additive {
  const code = tag.replace(/^[a-z]{2}:/, '').toLowerCase()
  const known =
    BY_CODE.get(code) ??
    BY_CODE.get(code.replace(/^(e\d+[a-z]?).*$/, '$1')) ??
    BY_CODE.get(code.replace(/^(e\d+).*$/, '$1'))
  return { code: code.charAt(0).toUpperCase() + code.slice(1), name: known?.name ?? '', risk: known?.risk ?? null }
}
